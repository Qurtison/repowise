SPEC = LanguageSpec(
    tag="gdscript",
    display_name="GDScript",
    # ``res://`` is an absolute, unambiguous project-root path and preload()
    # takes a string literal, so import resolution is exact — no heuristics.
    import_support="full",
    extensions=frozenset({".gd"}),
    grammar_package="tree_sitter_gdscript",
    scm_file="gdscript.scm",
    # A .gd file IS a class. Its ``extends`` sits at file scope beside
    # ``class_name`` rather than inside a class node, so the heritage
    # extractor reaches it from the class_name_statement's parent; inner
    # classes carry their own. See extractors/heritage/gdscript.py.
    heritage_node_types=frozenset({"class_name_statement", "class_definition"}),
    manifest_files=("project.godot",),
    # Godot 4 caches imported assets under .godot/, Godot 3 under .import/.
    # Both are regenerated build output and must never be indexed.
    blocked_dirs=(".godot", ".import"),
    # Sidecar metadata Godot writes next to every imported asset.
    blocked_extensions=(".import",),
    # GUT names tests test_foo.gd; GdUnit4 names them foo_test.gd.
    test_stem_prefixes=("test_",),
    test_stem_suffixes=("_test",),
    builtin_calls=_GDSCRIPT_BUILTIN_CALLS,
    builtin_parents=_GODOT_BASE_CLASSES,
    color_hex="#355570",
)
